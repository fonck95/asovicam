// Pre-encodes source images into responsive AVIF/WebP sizes plus a tiny
// blurred LQIP, then writes a manifest the client imports for <picture> srcset.
//
// Source images live in public/. Outputs go to public/img/ and src/data/imageManifest.ts.
import sharp from 'sharp';
import { readdir, mkdir, writeFile, stat } from 'node:fs/promises';
import { join, basename, extname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const SOURCE_DIR = join(ROOT, 'images-src');
const PUBLIC_DIR = join(ROOT, 'public');
const OUT_DIR = join(PUBLIC_DIR, 'img');
const MANIFEST = join(ROOT, 'src', 'data', 'imageManifest.ts');

const WIDTHS = [480, 960, 1440, 1920];
const WEBP_QUALITY = 72;
const AVIF_QUALITY = 48;
const LQIP_WIDTH = 24;

const SOURCES = [
  { file: 'milpa.jpg', directory: SOURCE_DIR },
  { file: 'steps-milpa.jpg', directory: SOURCE_DIR },
  { file: 'IMG_1093.jpeg', directory: ROOT, slug: 'hero-cultivo', widths: [320, 640, 960] },
  { file: 'IMG_1111.jpeg', directory: ROOT, slug: 'hero-recorrido', widths: [320, 640, 960] },
  { file: 'IMG_1122.jpeg', directory: ROOT, slug: 'hero-siembra', widths: [320, 640, 960] },
  { file: 'IMG_1137.jpeg', directory: ROOT, slug: 'hero-camino', widths: [320, 640, 960] },
  { file: 'IMG_1158.jpeg', directory: ROOT, slug: 'hero-territorio' },
  { file: 'logo.jpg', directory: PUBLIC_DIR, slug: 'asovicam-logo', widths: [128, 256, 384] },
];

await mkdir(OUT_DIR, { recursive: true });

const entries = {};

for (const source of SOURCES) {
  const { file, directory } = source;
  const srcPath = join(directory, file);
  try {
    await stat(srcPath);
  } catch {
    console.warn(`[optimize-images] missing ${file}, skipping`);
    continue;
  }

  const slug = source.slug ?? basename(file, extname(file));
  const meta = await sharp(srcPath).metadata();
  const naturalW = meta.width ?? 0;
  const naturalH = meta.height ?? 0;
  const aspect = naturalW && naturalH ? naturalW / naturalH : 16 / 9;

  const variants = [];
  for (const w of source.widths ?? WIDTHS) {
    if (w > naturalW) continue;
    const webpName = `${slug}-${w}.webp`;
    const avifName = `${slug}-${w}.avif`;
    const prepared = sharp(srcPath)
      .autoOrient()
      .resize({ width: w, withoutEnlargement: true });

    await Promise.all([
      prepared
        .clone()
        .webp({ quality: WEBP_QUALITY, effort: 5, smartSubsample: true })
        .toFile(join(OUT_DIR, webpName)),
      prepared
        .clone()
        .avif({ quality: AVIF_QUALITY, effort: 5, chromaSubsampling: '4:2:0' })
        .toFile(join(OUT_DIR, avifName)),
    ]);
    variants.push({
      width: w,
      src: `/img/${webpName}`,
      avif: `/img/${avifName}`,
    });
  }

  const lqipBuffer = await sharp(srcPath)
    .autoOrient()
    .resize({ width: LQIP_WIDTH })
    .blur(0.6)
    .webp({ quality: 35 })
    .toBuffer();
  const lqip = `data:image/webp;base64,${lqipBuffer.toString('base64')}`;

  entries[`/${file}`] = {
    slug,
    aspectRatio: aspect,
    naturalWidth: naturalW,
    naturalHeight: naturalH,
    lqip,
    variants,
  };
  console.log(`[optimize-images] ${file} → ${variants.length} variants, lqip=${lqipBuffer.length}b`);
}

const lines = [
  '// AUTO-GENERATED by scripts/optimize-images.mjs — do not edit by hand.',
  'export interface ImageVariant { width: number; src: string; avif?: string }',
  'export interface ImageManifestEntry {',
  '  slug: string;',
  '  aspectRatio: number;',
  '  naturalWidth: number;',
  '  naturalHeight: number;',
  '  lqip: string;',
  '  variants: ImageVariant[];',
  '}',
  '',
  `export const imageManifest: Record<string, ImageManifestEntry> = ${JSON.stringify(entries, null, 2)};`,
  '',
];
await writeFile(MANIFEST, lines.join('\n'));

const sizes = await readdir(OUT_DIR);
console.log(`[optimize-images] wrote ${sizes.length} files to public/img/ and manifest at ${MANIFEST}`);
